from datetime import datetime, timezone
from sqlalchemy import Column, Integer, String, Float, DateTime, Text, ForeignKey
from sqlalchemy.orm import relationship
from app.database.connection import Base


def utc_now():
    return datetime.now(timezone.utc)


class Alert(Base):
    """
    ORM Model for Threat Alerts generated by detection/rules.
    """
    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    owner_user_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True, index=True)
    event_id = Column(Integer, ForeignKey("security_events.id", ondelete="SET NULL"), nullable=True, index=True)
    threat_type = Column(String(50), nullable=False, index=True) # e.g. DOS_DDOS, BRUTE_FORCE, etc.
    confidence = Column(Float, nullable=False, default=0.0)      # 0.0 to 1.0
    risk_level = Column(String(20), nullable=False, index=True)  # LOW, MEDIUM, HIGH, CRITICAL
    message = Column(Text, nullable=False)
    status = Column(String(20), default="NEW", nullable=False, index=True) # NEW, ACKNOWLEDGED, RESOLVED, IGNORED
    created_at = Column(DateTime, default=utc_now, nullable=False)

    # Relationships
    event = relationship("SecurityEvent", back_populates="alerts")
    incidents = relationship("Incident", back_populates="alert", cascade="all, delete-orphan")
